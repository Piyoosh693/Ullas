const express = require('express');
const { requireAuth } = require('../auth');
const { isTestMode, query, errorResponse } = require('./helpers');
const notifications = require('../notification-store');
const router = express.Router();
function mapRow(row) { return { id: row.id, userId: row.user_id, type: row.type, message: row.message, read: row.is_read, createdAt: row.created_at }; }
router.get('/notifications', requireAuth, async (req, res) => {
  try {
    const list = isTestMode()
      ? [...notifications.values()].filter((item) => item.userId === req.user.id || req.user.role === 'admin')
      : (await query(req.user.role === 'admin' ? 'SELECT * FROM notifications ORDER BY created_at DESC LIMIT 500' : 'SELECT * FROM notifications WHERE user_id=$1 ORDER BY created_at DESC LIMIT 200', req.user.role === 'admin' ? [] : [req.user.id])).rows.map(mapRow);
    return res.json({ notifications: list });
  } catch (error) { return errorResponse(res, error, 'Could not load notifications'); }
});
router.post('/notifications', requireAuth, (req, res) => res.status(405).json({ error: 'Notifications are generated by Ullas activity and cannot be created directly' }));
router.patch('/notifications/:id/read', requireAuth, async (req, res) => {
  try {
    if (isTestMode()) {
      const item = notifications.get(req.params.id);
      if (!item) return res.status(404).json({ error: 'Notification not found' });
      if (item.userId !== req.user.id && req.user.role !== 'admin') return res.status(403).json({ error: 'Forbidden' });
      const updated = { ...item, read: true }; notifications.set(item.id, updated); return res.json({ notification: updated });
    }
    const result = await query('UPDATE notifications SET is_read=TRUE WHERE id=$1 AND (user_id=$2 OR $3::boolean) RETURNING *', [req.params.id, req.user.id, req.user.role === 'admin']);
    if (!result.rowCount) return res.status(404).json({ error: 'Notification not found or access denied' });
    return res.json({ notification: mapRow(result.rows[0]) });
  } catch (error) { return errorResponse(res, error, 'Could not update notification'); }
});
module.exports = { router, notifications };
